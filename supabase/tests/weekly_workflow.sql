begin;
do $$
declare admin_id uuid; branch_id uuid; location uuid; product uuid; order1 uuid; order2 uuid; line1 uuid; line2 uuid;
  request_id uuid; weekly_id uuid; data jsonb; stock integer; stamp timestamptz; sent timestamptz; failed boolean; other_order uuid;
begin
  select id into admin_id from public.profiles where role::text='CENTRAL_ADMIN' and status::text='active' limit 1;
  select id,location_id into branch_id,location from public.profiles where role::text='BRANCH_MANAGER' and status::text='active' and location_id is not null limit 1;
  if admin_id is null or branch_id is null then raise exception 'Active admin and branch manager required.'; end if;
  perform set_config('request.jwt.claim.sub',admin_id::text,true);
  insert into public.catalog_items(name,category,unit_type,default_price,available_stock) values('Weekly test (rolled back)','Pantry','Bucket',2,10) returning id into product;
  insert into public.orders(location_id,order_number) values(location,-2147483200) returning id into order1;
  insert into public.order_lines(order_id,item_id,quantity,fulfilled_quantity,unit_price,is_taxable,line_total) values(order1,product,5,5,2,true,10) returning id into line1;
  execute 'set local role authenticated';
  update public.orders set status='READY' where id=order1;
  perform set_config('request.jwt.claim.sub',branch_id::text,true);
  if public.submit_pickup(order1,jsonb_build_array(jsonb_build_object('line_id',line1,'quantity',7)),'',false)<>'PENDING' then raise exception 'Above-request pickup was not accepted for approval'; end if;
  select id into request_id from public.pickup_requests where order_id=order1 and status='PENDING';
  perform set_config('request.jwt.claim.sub',admin_id::text,true);
  perform public.review_pickup(request_id,true,'','{}');
  select available_stock into stock from public.catalog_items where id=product;
  if stock<>3 then raise exception 'Extra pickup stock deduction incorrect'; end if;
  insert into public.orders(location_id,order_number) values(location,-2147483199) returning id into order2;
  insert into public.order_lines(order_id,item_id,quantity,fulfilled_quantity,unit_price,is_taxable,line_total) values(order2,product,2,2,2,false,4) returning id into line2;
  update public.orders set status='READY' where id=order2;
  if public.submit_pickup(order2,jsonb_build_array(jsonb_build_object('line_id',line2,'quantity',2)),'',false)<>'COMPLETED' then raise exception 'Admin pickup fallback failed'; end if;
  weekly_id:=public.create_weekly_invoice(location,(now() at time zone 'America/Toronto')::date,(now() at time zone 'America/Toronto')::date,array[order1,order2]);
  data:=public.weekly_invoice_details(weekly_id,true);
  if (data->>'total')::numeric<>19.82 or jsonb_array_length(data->'orders')<>2 then raise exception 'Combined weekly invoice totals incorrect: %',data; end if;
  failed:=false;
  begin perform public.create_weekly_invoice(location,(now() at time zone 'America/Toronto')::date,(now() at time zone 'America/Toronto')::date,array[order1]); exception when raise_exception then failed:=true; end;
  if not failed then raise exception 'An order was billed twice'; end if;
  select updated_at into stamp from public.orders where id=order1;
  perform public.edit_invoice(order1,jsonb_build_array(jsonb_build_object('line_id',line1,'quantity',6,'unit_price',2,'is_taxable',false)),'',stamp);
  if not exists(select 1 from public.order_lines where id=line1 and fulfilled_quantity=7 and invoice_quantity=6) then raise exception 'Billing edit changed physical pickup'; end if;
  select available_stock into stock from public.catalog_items where id=product;
  if stock<>1 then raise exception 'Billing edit changed stock'; end if;
  select updated_at into stamp from public.orders where id=order1;
  failed:=false;
  begin perform public.edit_invoice(order1,jsonb_build_array(jsonb_build_object('line_id',line1,'quantity',6,'unit_price',3,'is_taxable',false)),'',stamp); exception when raise_exception then failed:=true; end;
  if not failed then raise exception 'Invoice price could be edited'; end if;
  sent:=public.send_weekly_invoice(weekly_id);
  if public.send_weekly_invoice(weekly_id) is distinct from sent then raise exception 'Duplicate weekly send was not idempotent'; end if;
  perform set_config('request.jwt.claim.sub',branch_id::text,true);
  data:=public.weekly_invoice_details(weekly_id,true);
  if (data->>'total')::numeric<>16 then raise exception 'Branch could not read published weekly invoice'; end if;
  failed:=false;
  begin perform public.send_weekly_invoice(weekly_id); exception when raise_exception then failed:=true; end;
  if not failed then raise exception 'Branch sent weekly invoice'; end if;
  perform set_config('request.jwt.claim.sub',admin_id::text,true);
  select updated_at into stamp from public.orders where id=order1;
  perform public.edit_invoice(order1,jsonb_build_array(jsonb_build_object('line_id',line1,'quantity',5,'unit_price',2,'is_taxable',true)),'',stamp);
  perform set_config('request.jwt.claim.sub',branch_id::text,true);
  if (public.weekly_invoice_details(weekly_id,true)->>'total')::numeric<>16 then raise exception 'Unsent correction replaced published invoice'; end if;
  perform set_config('request.jwt.claim.sub',admin_id::text,true);
  perform public.send_weekly_invoice(weekly_id);
  if (public.weekly_invoice_details(weekly_id,false)->>'total')::numeric<>15.3 or (select count(*) from public.weekly_invoice_publications where weekly_invoice_id=weekly_id)<>2 then raise exception 'Weekly revision publication/history incorrect'; end if;

  -- Physically collected extras: rejection does not pretend items returned.
  execute 'set local role postgres';
  insert into public.catalog_items(name,category,unit_type,default_price,available_stock) values('Return test (rolled back)','Pantry','Bucket',2,10) returning id into product;
  insert into public.orders(location_id,order_number) values(location,-2147483198) returning id into order1;
  insert into public.order_lines(order_id,item_id,quantity,fulfilled_quantity,unit_price,is_taxable,line_total) values(order1,product,5,5,2,false,10) returning id into line1;
  execute 'set local role authenticated';
  update public.orders set status='READY' where id=order1;
  perform set_config('request.jwt.claim.sub',branch_id::text,true);
  perform public.submit_pickup(order1,jsonb_build_array(jsonb_build_object('line_id',line1,'quantity',7)),'',true);
  select id into request_id from public.pickup_requests where order_id=order1 and status='PENDING';
  select available_stock into stock from public.catalog_items where id=product;
  if stock<>3 then raise exception 'Collected extras were not recorded against available stock'; end if;
  perform set_config('request.jwt.claim.sub',admin_id::text,true);
  if public.review_pickup(request_id,false,'','{}')<>'RETURN_PENDING' then raise exception 'Rejection did not request extras back'; end if;
  select available_stock into stock from public.catalog_items where id=product;
  if stock<>3 then raise exception 'Rejection prematurely credited stock'; end if;
  failed:=false;
  begin perform public.create_weekly_invoice(location,(now() at time zone 'America/Toronto')::date,(now() at time zone 'America/Toronto')::date,array[order1]); exception when raise_exception then failed:=true; end;
  if not failed then raise exception 'Outstanding return was billed'; end if;
  perform public.receive_pickup_return(request_id,'Received two buckets');
  select available_stock into stock from public.catalog_items where id=product;
  if stock<>5 or not exists(select 1 from public.orders where id=order1 and status='COMPLETED') then raise exception 'Return receipt stock/completion incorrect'; end if;
  failed:=false;
  begin perform public.receive_pickup_return(request_id,'Duplicate'); exception when raise_exception then failed:=true; end;
  if not failed then raise exception 'Return was credited twice'; end if;

  -- All available inventory allocated: register a shortfall, reject and return
  -- the extra two; returned allocated units must not become free stock.
  update public.catalog_items set available_stock=10 where id=product;
  insert into public.orders(location_id,order_number) values(location,-2147483197) returning id into order1;
  insert into public.order_lines(order_id,item_id,quantity,fulfilled_quantity,unit_price,is_taxable,line_total) values(order1,product,5,5,2,false,10) returning id into line1;
  update public.orders set status='READY' where id=order1;
  insert into public.orders(location_id,order_number) values(location,-2147483196) returning id into other_order;
  insert into public.order_lines(order_id,item_id,quantity,fulfilled_quantity,unit_price,is_taxable,line_total) values(other_order,product,5,5,2,false,10);
  update public.orders set status='READY' where id=other_order;
  perform set_config('request.jwt.claim.sub',branch_id::text,true);
  perform public.submit_pickup(order1,jsonb_build_array(jsonb_build_object('line_id',line1,'quantity',7)),'',true);
  select id into request_id from public.pickup_requests where order_id=order1 and status='PENDING';
  perform set_config('request.jwt.claim.sub',admin_id::text,true);
  failed:=false;
  begin perform public.review_pickup(request_id,true,'','{}'); exception when raise_exception then failed:=true; end;
  if not failed then raise exception 'Allocated-stock shortfall was approved'; end if;
  perform public.review_pickup(request_id,false,'Extra two needed back','{}');
  perform public.receive_pickup_return(request_id,'Received');
  select available_stock into stock from public.catalog_items where id=product;
  if stock<>0 then raise exception 'Returned allocated inventory became unallocated stock'; end if;
  execute 'set local role postgres';
end; $$;
rollback;
select 'Passed: 5 ordered / 7 pickup, optional notes, admin completion, collected-extra rejection and returns, allocated-stock shortfalls, weekly grouping, duplicate billing prevention, locked prices, billing-only edits, published revisions, and branch permissions. All fixtures rolled back.' as result;
